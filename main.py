"""
周报助手 - 命令行工具
========================
功能：
  1. 记录今天的工作
  2. 查看所有历史记录
  3. 生成最近 7 天的周报
  4. 退出程序

数据保存在 weekly_report.txt 文件中，每条记录包含日期和工作内容。
"""

import os
from datetime import datetime, timedelta

# ============================================================
# 数据文件名（程序运行时自动创建，不需要手动新建）
# ============================================================
DATA_FILE = "weekly_report.txt"


# ============================================================
# 工具函数（每个函数负责一个小功能）
# ============================================================

def 获取今天的日期():
    """返回今天日期的字符串，格式如：2026-06-06"""
    return datetime.now().strftime("%Y-%m-%d")


def 获取星期几():
    """返回今天是星期几，如：星期一"""
    星期列表 = ["星期一", "星期二", "星期三", "星期四", "星期五", "星期六", "星期日"]
    return 星期列表[datetime.now().weekday()]


def 确保文件存在():
    """如果数据文件不存在，就创建一个空的"""
    if not os.path.exists(DATA_FILE):
        with open(DATA_FILE, "w", encoding="utf-8") as f:
            pass  # 只创建空文件，不写任何内容


# ============================================================
# 核心功能函数
# ============================================================

def 记录今天的工作():
    """
    功能 1：记录今天的工作
    用户输入工作内容后，保存到数据文件，格式为：
    2026-06-06 星期五
      今天做了xxxxx
    """
    print("\n" + "=" * 50)
    print("[记录]  记录今天的工作")
    print("=" * 50)

    今天的日期 = 获取今天的日期()
    星期 = 获取星期几()

    print(f"\n[日期] 今天日期：{今天的日期} {星期}")
    print("\n请输入你今天的工作内容（可以多行，输入完毕后按一次回车，")
    print("然后在空行再按一次回车确认提交）:\n")

    # 支持多行输入：一直读直到遇到空行
    内容列表 = []
    while True:
        一行 = input()
        if 一行 == "":
            # 如果第一行就是空的，说明用户没写任何内容
            if len(内容列表) == 0:
                print("[警告] 你还没有输入任何内容，请重新输入：")
                continue
            else:
                break
        内容列表.append(一行)

    # 把多行内容拼成一段文字
    工作内容 = "\n".join(内容列表)

    # 写入数据文件（追加模式，不会覆盖之前的内容）
    with open(DATA_FILE, "a", encoding="utf-8") as f:
        f.write(f"{今天的日期} {星期}\n")
        f.write(f"  {工作内容}\n")
        f.write("\n")  # 加一个空行，让不同日期的记录之间有空隙

    print("\n[完成] 工作记录已保存！\n")


def 查看历史记录():
    """
    功能 2：查看所有历史记录
    读取整个数据文件并显示
    """
    print("\n" + "=" * 50)
    print("[查看]  查看历史记录")
    print("=" * 50 + "\n")

    确保文件存在()

    with open(DATA_FILE, "r", encoding="utf-8") as f:
        内容 = f.read()

    if 内容.strip() == "":
        print("[空] 还没有任何工作记录，快去记录今天的工作吧！\n")
    else:
        print(内容)
        print("-" * 50)
        # 统计有多少条记录
        记录数 = 内容.count("星期")  # 简单统计：数"星期"出现了几次
        print(f"[统计] 共 {记录数} 条记录\n")


def 生成周报():
    """
    功能 3：生成简单周报
    读取数据文件，筛选出最近 7 天的记录并显示
    """
    print("\n" + "=" * 50)
    print("[周报]  生成本周周报")
    print("=" * 50 + "\n")

    确保文件存在()

    # 计算最近 7 天的日期列表
    # 比如今天是 6月6日，那就生成 [6月6日, 6月5日, ..., 5月31日]
    今天 = datetime.now()
    最近七天日期 = []
    for i in range(7):
        某天 = 今天 - timedelta(days=i)
        最近七天日期.append(某天.strftime("%Y-%m-%d"))

    # 读取数据文件所有内容
    with open(DATA_FILE, "r", encoding="utf-8") as f:
        全部内容 = f.read()

    if 全部内容.strip() == "":
        print("[空] 还没有任何工作记录，快去记录今天的工作吧！\n")
        return

    # 按空行分割，每条记录是一块
    所有记录 = 全部内容.strip().split("\n\n")

    # 找出属于最近 7 天的记录
    找到的记录 = []
    for 记录 in 所有记录:
        # 每条记录的第一行格式："2026-06-06 星期五"
        第一行 = 记录.split("\n")[0].strip()
        # 提取日期部分："2026-06-06"
        if " " in 第一行:
            记录日期 = 第一行.split(" ")[0]
        elif "  " in 第一行:
            记录日期 = 第一行.split("  ")[0]
        else:
            continue

        if 记录日期 in 最近七天日期:
            找到的记录.append(记录)

    # 显示结果
    if len(找到的记录) == 0:
        print("[空] 最近 7 天还没有工作记录。\n")
    else:
        print(f"[日期] 最近 7 天共有 {len(找到的记录)} 条记录：\n")
        # 让最新的记录显示在最前面
        for 记录 in reversed(找到的记录):
            print(记录)
            print()
        print("-" * 50)
        print(f"[统计] 周报共 {len(找到的记录)} 条记录\n")


# ============================================================
# 菜单和主程序
# ============================================================

def 显示菜单():
    """打印主菜单"""
    print("\n" + "=" * 50)
    print("          [周报] 周报助手  v1.0")
    print("=" * 50)
    print("  1. [记] 记录今天的工作")
    print("  2. [看] 查看历史记录")
    print("  3. [报] 生成本周周报")
    print("  4. [退] 退出程序")
    print("=" * 50)


def 主程序():
    """
    程序入口：一直循环显示菜单，根据用户选择执行对应功能。
    用户输入 4 或者按 Ctrl+C 时退出。
    """
    print("\n[欢迎] 欢迎使用周报助手！我是你的编程小帮手，帮你记录每天的工作~")

    while True:
        显示菜单()

        try:
            选择 = input("\n请选择功能（输入数字 1-4）：").strip()
        except (EOFError, KeyboardInterrupt):
            print("\n\n[再见] 感谢使用周报助手，再见！")
            break

        if 选择 == "1":
            记录今天的工作()
        elif 选择 == "2":
            查看历史记录()
        elif 选择 == "3":
            生成周报()
        elif 选择 == "4":
            print("\n[再见] 感谢使用周报助手，再见！\n")
            break
        else:
            print("\n[警告] 输入有误，请输入 1、2、3 或 4！")


# ============================================================
# 程序入口
# ============================================================
if __name__ == "__main__":
    主程序()
