def 生成周报():
    """
    功能 3：生成简单周报（表格形式）
    读取数据文件，筛选出最近 7 天的记录，用表格显示。
    """
    print()
    画分割线("=", 50)
    print("  [周报]  生成本周周报")
    画分割线("=", 50)
    print()

    确保文件存在()

    # 计算最近 7 天的日期列表（YYYY-MM-DD 格式用于比较）
    今天 = datetime.now()
    最近七天日期 = []
    for i in range(7):
        某天 = 今天 - timedelta(days=i)
        最近七天日期.append(某天.strftime("%Y-%m-%d"))

    # 读取数据文件所有内容
    with open(DATA_FILE, "r", encoding="utf-8") as f:
        全部内容 = f.read()

    if 全部内容.strip() == "":
        print("  [空] 还没有任何工作记录，快去记录今天的工作吧！")
        print()
        return

    # 按空行分割，每条记录是一块
    所有记录 = 全部内容.strip().split("\n\n")

    # 找出属于最近 7 天的记录
    找到的记录 = []
    for 记录 in 所有记录:
        记录日期 = 从记录中提取日期(记录)
        if 记录日期 and 记录日期 in 最近七天日期:
            找到的记录.append(记录)

    # ---- 表格形式输出 ----
    if len(找到的记录) == 0:
        print("  [空] 最近 7 天还没有工作记录。")
        print()
        return

    print(f"  最近 7 天共有 {len(找到的记录)} 条记录：")
    print()

    # 计算表格列宽
    # 第一列：日期+星期（如 "06月06日 星期六"）
    # 第二列：工作内容
    列宽列表 = [20, 50]

    画表格线(列宽列表)
    画表格行(["日期", "工作内容"], 列宽列表)
    画表格线(列宽列表)

    # 让最新的记录显示在最前面
    for 记录 in reversed(找到的记录):
        行列表 = 记录.split("\n")
        第一行 = 行列表[0].strip()  # 日期行

        # 把日期格式化为更短的显示形式：从 "2026年06月06日 星期六" 提取 "06月06日 星期六"
        日期显示 = 格式化日期显示用(第一行)

        # 工作内容（去掉每行前面可能存在的缩进空格）
        内容行列表 = [行.strip() for 行 in 行列表[1:] if 行.strip()]
        工作内容显示 = "；".join(内容行列表)

        画表格行([日期显示, 工作内容显示], 列宽列表)

    画表格线(列宽列表)
    print()
    画分割线("-", 50)
    print(f"  [统计] 周报共 {len(找到的记录)} 条记录")
    print()


def 格式化日期显示用(日期行):
    """
    把存储的日期行格式化为表格显示用的短格式。
    输入: "2026年06月06日 星期六" 或 "2026-06-06 星期六"
    输出: "06月06日 星期六"
    """
    # 去掉年份部分
    # 新格式: 2026年06月06日 → 06月06日
    m = re.match(r"\d{4}年(\d{2}月\d{2}日)", 日期行)
    if m:
        return m.group(1) + " " + 日期行.split(" ")[-1] if " " in 日期行 else m.group(1)

    # 旧格式: 2026-06-06 → 06-06
    m = re.match(r"\d{4}-(\d{2}-\d{2})", 日期行)
    if m:
        return m.group(1) + " " + 日期行.split(" ")[-1] if " " in 日期行 else m.group(1)

    # 无法识别，原样返回
    return 日期行


def 按日期查找():
    """
    功能 4：按日期查找记录
    用户输入日期（支持多种格式），查找并显示匹配的记录。
    """
    print()
    画分割线("=", 50)
    print("  [查找]  按日期查找记录")
    画分割线("=", 50)
    print()

    确保文件存在()

    # 读取所有记录
    with open(DATA_FILE, "r", encoding="utf-8") as f:
        全部内容 = f.read()

    if 全部内容.strip() == "":
        print("  [空] 还没有任何工作记录，快去记录今天的工作吧！")
        print()
        return

    print("  支持的日期格式：")
    print("    2026-06-06  /  2026年6月6日  /  6月6日  /  6-6")
    print()
    用户输入 = input("  请输入要查找的日期：").strip()

    if 用户输入 == "":
        print("  [警告] 没有输入日期，已取消查找。")
        print()
        return

    # 把用户输入的日期转成 YYYY-MM-DD 格式
    目标日期 = 解析日期(用户输入)
    if 目标日期 is None:
        print(f"  [警告] 无法识别日期格式「{用户输入}」，请重新输入。")
        print()
        return

    # 按空行分割所有记录
    所有记录 = 全部内容.strip().split("\n\n")

    # 逐条匹配
    匹配记录 = []
    for 记录 in 所有记录:
        记录日期 = 从记录中提取日期(记录)
        if 记录日期 == 目标日期:
            匹配记录.append(记录)

    # 显示结果
    if len(匹配记录) == 0:
        print()
        print(f"  [空] 没有找到 {目标日期} 的工作记录。")
        print()
    else:
        print()
        print(f"  找到 {len(匹配记录)} 条记录：")
        print()
        画分割线("-", 50)
        for 记录 in 匹配记录:
            print(记录)
            print()
        画分割线("-", 50)
    print()


def 导出为CSV():
    """
    [实验功能] 将历史记录导出为 CSV 文件。
    CSV 可以用 Excel 打开，方便在其他软件中处理数据。
    注意：这个功能还在测试中，可能不完善！
    """
    print()
    画分割线("=", 50)
    print("  [实验]  导出为 CSV 文件")
    画分割线("=", 50)
    print()
    print("  [警告] 这是实验功能，可能不稳定！")

    确保文件存在()

    with open(DATA_FILE, "r", encoding="utf-8") as f:
        全部内容 = f.read()

    if 全部内容.strip() == "":
        print("  [空] 还没有任何工作记录，无法导出。")
        print()
        return

    # 按空行分割记录
    所有记录 = 全部内容.strip().split("\n\n")

    # 写入 CSV 文件
    CSV文件名 = "周报数据.csv"
    with open(CSV文件名, "w", encoding="utf-8-sig") as f:
        # CSV 表头（用 utf-8-sig 编码，Excel 能正确打开中文）
        f.write("日期,星期,工作内容\n")
        for 记录 in 所有记录:
            行列表 = 记录.split("\n")
            日期行 = 行列表[0].strip()
            # 分离日期和星期
            if " " in 日期行:
                日期, 星期 = 日期行.split(" ", 1)
            else:
                日期, 星期 = 日期行, ""
            # 工作内容（多行合并）
            内容 = "；".join([行.strip() for 行 in 行列表[1:] if 行.strip()])
            # CSV 行（字段中的逗号用中文逗号替换，避免错列）
            f.write(f"{日期},{星期},{内容}\n")

    print(f"  [完成] 已导出到 {CSV文件名}，可以用 Excel 打开！")
    print()


