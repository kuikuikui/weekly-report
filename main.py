def 解析日期(日期文本):
    """
    从各种日期格式中提取 YYYY-MM-DD 格式，用于内部比较。
    支持的格式：
      - 2026-06-06（旧格式）
      - 2026年06月06日（新格式）
      - 2026年6月6日（不带前导零）
      - 6月6日 / 6-6（省略年份，自动补当前年份）
    如果解析不出来，返回 None。
    """
    日期文本 = 日期文本.strip()

    # 1. 尝试匹配 YYYY-MM-DD（旧格式）
    m = re.match(r"(\d{4})-(\d{1,2})-(\d{1,2})", 日期文本)
    if m:
        return f"{int(m.group(1)):04d}-{int(m.group(2)):02d}-{int(m.group(3)):02d}"

    # 2. 尝试匹配 YYYY年MM月DD日（新格式）
    m = re.match(r"(\d{4})年(\d{1,2})月(\d{1,2})日", 日期文本)
    if m:
        return f"{int(m.group(1)):04d}-{int(m.group(2)):02d}-{int(m.group(3)):02d}"

    # 3. 尝试匹配 MM月DD日（省略年份，用今年）
    m = re.match(r"(\d{1,2})月(\d{1,2})日", 日期文本)
    if m:
        今年 = datetime.now().year
        return f"{今年:04d}-{int(m.group(1)):02d}-{int(m.group(2)):02d}"

    # 4. 尝试匹配 MM-DD（省略年份，用今年）
    m = re.match(r"(\d{1,2})-(\d{1,2})$", 日期文本)
    if m:
        今年 = datetime.now().year
        return f"{今年:04d}-{int(m.group(1)):02d}-{int(m.group(2)):02d}"

    # 5. 尝试匹配纯数字 YYYYMMDD
    m = re.match(r"(\d{4})(\d{2})(\d{2})", 日期文本)
    if m:
        return f"{int(m.group(1)):04d}-{int(m.group(2)):02d}-{int(m.group(3)):02d}"

    return None


def 从记录中提取日期(记录):
    """
    从一条记录的文本中提取 YYYY-MM-DD 格式的日期。
    记录第一行可能是：
      - 2026-06-06 星期六（旧格式）
      - 2026年06月06日 星期六（新格式）
    """
    第一行 = 记录.split("\n")[0].strip()
    # 日期和星期之间用空格分开
    # 先找第一个空格 —— 日期部分就是空格前面的所有内容
    空格位置 = 第一行.find(" ")
    if 空格位置 == -1:
        # 没有空格，说明格式不对，用正则从整行里提取
        return 解析日期(第一行)
    日期部分 = 第一行[:空格位置]
    return 解析日期(日期部分)


def 画分割线(字符="-", 长度=50):
    """画一条分割线，方便重复使用"""
    print(字符 * 长度)


def 画表格线(列宽列表):
    """
    画表格的横线，如：+----------+------+--------------------------------+
    列宽列表 如 [10, 6, 30] 表示三列的宽度
    """
    各部分 = ["+" + "-" * (宽 + 2) for 宽 in 列宽列表]
    print("".join(各部分) + "+")


def 画表格行(单元格列表, 列宽列表):
    """
    画表格的一行数据，如：| 2026-06-06 | 六 | 完成了登录页面的开发    |
    单元格列表 和 列宽列表 一一对应
    """
    # 把每个单元格裁剪或补空格到对应宽度
    显示格 = []
    for 格, 宽 in zip(单元格列表, 列宽列表):
        # 中文占两个字符宽，这里做一个简单的中文宽度计算
        # 实际显示时通过填充空格来对齐
        显示格.append(对齐文本(格, 宽))
    print("| " + " | ".join(显示格) + " |")


def 对齐文本(文本, 目标宽度):
    """
    把文本对齐到目标宽度（考虑中文字符占两个英文字符宽度）。
    在 Windows 命令行中，中文字符显示宽度 ≈ 2 个英文字符。
    如果文本超出宽度，就截断并加 ".."。
    """
    当前宽度 = 计算显示宽度(文本)
    if 当前宽度 > 目标宽度:
        # 文本太长，截断
        return 截断文本(文本, 目标宽度 - 2) + ".."
    else:
        # 文本不够长，后面补空格
        return 文本 + " " * (目标宽度 - 当前宽度)


def 计算显示宽度(文本):
    """
    计算文本在命令行中的显示宽度。
    中文字符和全角符号占 2，英文和数字占 1。
    """
    宽 = 0
    for 字符 in 文本:
        # Unicode 码点大于 0x2000 的基本都是全角字符
        if ord(字符) > 0x2000:
            宽 += 2
        else:
            宽 += 1
    return 宽


def 截断文本(文本, 目标宽度):
    """按显示宽度截断文本"""
    结果 = ""
    当前宽 = 0
    for 字符 in 文本:
        字宽 = 2 if ord(字符) > 0x2000 else 1
        if 当前宽 + 字宽 > 目标宽度:
            break
        结果 += 字符
        当前宽 += 字宽
    return 结果


